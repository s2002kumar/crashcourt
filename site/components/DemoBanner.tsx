// "Demo data — not a result", on every page that renders anything from a fixture. Whether it shows is
// decided by the provenance of the artifacts the page renders (lib/provenance.ts): never by the route,
// a build flag, or the environment. It has no close control and stays pinned to the top of the viewport
// while the page scrolls, so a screenshot of any part of a demo page carries it.
//
// A server component: its markup reaches the export only on pages that render it, which is what lets the
// release guard fail any build whose output holds the marker attribute.

import { DEMO_BANNER_ATTRIBUTE, showsFixture, type Sourced } from "@/lib/provenance";

export function DemoBanner({ sources }: { sources: readonly Sourced[] }) {
  if (!showsFixture(sources)) return null;
  return (
    <div
      role="note"
      aria-label="Demo data"
      {...{ [DEMO_BANNER_ATTRIBUTE]: "" }}
      className="demo-banner sticky top-0 z-40 flex items-start gap-3 rounded-panel border border-ink bg-ink px-4 py-2.5 text-sm text-bg shadow-lg"
    >
      <span
        aria-hidden="true"
        className="mt-1 h-3 w-6 shrink-0 rounded-[1px]"
        style={{
          backgroundImage:
            "repeating-linear-gradient(135deg, var(--bg) 0 3px, transparent 3px 6px)",
        }}
      />
      <p>
        <strong className="font-semibold">Demo data — not a result.</strong> Generated by{" "}
        <code className="text-xs">crashcourt fixtures --demo</code>: nothing on this page was
        measured, and every id on it begins with &ldquo;DEMO&rdquo;.
      </p>
    </div>
  );
}
